"""Regenerate the exportable GDScript catalog from the canonical JSON fragment."""
import json
from pathlib import Path

project = Path(__file__).resolve().parents[3]
data = json.loads((project / "assets/workers/models/catalog.json").read_text(encoding="utf-8"))
# JSON literals are valid GDScript literals for this dictionary-only schema.
output = "extends RefCounted\n# Generated by tests/workers/models/generate_catalog.py; edit catalog.json.\nconst ENTRIES := " + json.dumps(data, indent=2, ensure_ascii=False) + "\n"
(project / "scripts/component_models/catalog_data.gd").write_text(output, encoding="utf-8", newline="")
